// JSON object member order can change across browser-tool and file boundaries.
// Array order, values, and extra members remain significant.
export function canonicalJSON(value) {
  return JSON.stringify(value, (_key, item) =>
    item && typeof item === "object" && !Array.isArray(item)
      ? Object.fromEntries(
          Object.keys(item)
            .sort()
            .map((key) => [key, item[key]]),
        )
      : item,
  );
}
